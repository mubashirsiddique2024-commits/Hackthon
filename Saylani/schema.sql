CREATE DATABASE IF NOT EXISTS peopleflow CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE peopleflow;

CREATE TABLE IF NOT EXISTS employees (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  role VARCHAR(160) NOT NULL,
  department VARCHAR(160) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  status ENUM('Active','On leave','Inactive') NOT NULL DEFAULT 'Active',
  joined DATE NOT NULL,
  salary DECIMAL(12,2) NOT NULL DEFAULT 0,
  initials VARCHAR(2) NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_employees_created (createdAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attendance (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  employeeId BIGINT UNSIGNED NOT NULL,
  employeeName VARCHAR(160) NOT NULL,
  date DATE NOT NULL,
  checkIn DATETIME NULL,
  checkOut DATETIME NULL,
  status ENUM('Present','Absent','On leave') NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY unique_employee_day (employeeId,date),
  INDEX idx_attendance_date (date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS leaves (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  employeeId BIGINT UNSIGNED NOT NULL,
  employee VARCHAR(160) NOT NULL,
  employeeName VARCHAR(160) NOT NULL,
  type VARCHAR(80) NOT NULL,
  `from` DATE NOT NULL,
  `to` DATE NOT NULL,
  days INT UNSIGNED NOT NULL,
  reason VARCHAR(1000) NOT NULL,
  status ENUM('Pending','Approved','Rejected') NOT NULL DEFAULT 'Pending',
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_leaves_employee_created (employeeId,createdAt),
  INDEX idx_leaves_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
